from __future__ import annotations

import subprocess
import sys
from pathlib import Path
from typing import Any

# launchd service helper, so the scheduler runs UNATTENDED (the gap between "works
# when I run it" and beta). Generates a LaunchAgent plist with the REAL paths filled in
# (current interpreter + repo root discovered at generation time, nothing to hand-
# edit), keeps the scheduler alive continuously (KeepAlive, restarts if it dies), and
# writes durable logs under data/logs/ (survives reboot, unlike /tmp). Install is
# offered but only runs launchctl on explicit confirmation.

LABEL = "com.mongoose.scheduler"


def _agents_dir() -> Path:
    return Path.home() / "Library" / "LaunchAgents"


def plist_path() -> Path:
    return _agents_dir() / f"{LABEL}.plist"


def _repo_root() -> Path:
    # src/mongoose/service.py -> repo root is three parents up.
    return Path(__file__).resolve().parents[2]


def _log_dir() -> Path:
    from .settings import get_settings
    # launchd requires ABSOLUTE paths; resolve in case data_dir is relative.
    d = (get_settings().data_dir / "logs").resolve()
    d.mkdir(parents=True, exist_ok=True)
    return d


def _mongoose_bin() -> str:
    """Prefer the installed `mongoose` console script next to this interpreter; fall
    back to `python -m mongoose.cli`. Either way the path is concrete, not a bare name
    that depends on PATH at launchd time."""
    cand = Path(sys.executable).with_name("mongoose")
    if cand.exists():
        return str(cand)
    return ""  # signal: use python -m


def render_plist() -> str:
    """Render the LaunchAgent plist with real, absolute paths discovered now."""
    out_log = _log_dir() / "scheduler.out.log"
    err_log = _log_dir() / "scheduler.err.log"
    root = _repo_root()
    binary = _mongoose_bin()
    if binary:
        program_args = [binary, "scheduler"]
    else:
        program_args = [sys.executable, "-m", "mongoose.cli", "scheduler"]
    args_xml = "\n".join(f"        <string>{a}</string>" for a in program_args)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Mongoose scheduler as a launchd agent. Generated by `mongoose service generate`
     with absolute paths filled in; do not hand-edit paths. KeepAlive restarts it if
     it dies. Logs: {out_log} / {err_log}.
     Manage with: mongoose service install|status|uninstall (or launchctl directly). -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>{LABEL}</string>
    <key>ProgramArguments</key>
    <array>
{args_xml}
    </array>
    <key>WorkingDirectory</key>
    <string>{root}</string>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>StandardOutPath</key>
    <string>{out_log}</string>
    <key>StandardErrorPath</key>
    <string>{err_log}</string>
    <key>ProcessType</key>
    <string>Background</string>
</dict>
</plist>
"""


def write_plist() -> Path:
    """Write the plist into ~/Library/LaunchAgents and return its path. Does NOT load
    it, generation and activation are separate so the user stays in control."""
    p = plist_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_plist(), encoding="utf-8")
    return p


def _launchctl(*args: str) -> tuple[int, str]:
    try:
        r = subprocess.run(["launchctl", *args], capture_output=True, text=True, timeout=15)
        return r.returncode, (r.stdout + r.stderr).strip()
    except FileNotFoundError:
        return 127, "launchctl not found (this command is macOS-only)"
    except Exception as exc:
        return 1, str(exc)


def install() -> dict[str, Any]:
    """Write the plist and load it with launchctl (activates the unattended scheduler).
    Idempotent: unloads first if already present."""
    p = write_plist()
    _launchctl("unload", str(p))  # ignore result; may not be loaded yet
    code, out = _launchctl("load", str(p))
    return {"ok": code == 0, "plist": str(p), "detail": out or "loaded"}


def uninstall() -> dict[str, Any]:
    """Unload the agent and remove the plist."""
    p = plist_path()
    code, out = _launchctl("unload", str(p))
    removed = False
    if p.exists():
        p.unlink()
        removed = True
    return {"ok": True, "plist": str(p), "unloaded": code == 0, "removed": removed, "detail": out}


def status() -> dict[str, Any]:
    """Report whether the agent is installed (plist present) and loaded (launchctl)."""
    p = plist_path()
    installed = p.exists()
    code, out = _launchctl("list", LABEL)
    loaded = code == 0
    out_log = _log_dir() / "scheduler.out.log"
    err_log = _log_dir() / "scheduler.err.log"
    return {
        "label": LABEL,
        "plist": str(p),
        "installed": installed,
        "loaded": loaded,
        "out_log": str(out_log),
        "err_log": str(err_log),
        "detail": out if loaded else "not loaded",
    }
